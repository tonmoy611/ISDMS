function renderBlock(b) {
  switch (b.kind) {
    case 'heading': return `<h3>${esc(b.text)}</h3>`;
    case 'keyvalue': return `<table class="kv">${b.rows.map(([k, v]) => `<tr><td>${esc(k)}</td><td>${esc(v)}</td></tr>`).join('')}</table>`;
    case 'table': {
      const cls = (i) => ({ r: ' class="r"', c: ' class="c"' }[b.align?.[i]] || '');
      return `<table><thead><tr>${b.head.map((h, i) => `<th${cls(i)}>${esc(h)}</th>`).join('')}</tr></thead><tbody>${b.rows.map((r) => `<tr>${r.map((c, i) => `<td${cls(i)}>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
    }
    case 'summary': return `<div class="summary">${b.items.map(([k, v]) => `<div>${esc(k)}<strong>${esc(v)}</strong></div>`).join('')}</div>`;
    case 'text': return `<p${b.tone === 'small' ? ' class="small"' : ''}>${esc(b.text)}</p>`;
    case 'signatures': return `<div class="sign">${b.labels.map((l) => `<div>${esc(l)}</div>`).join('')}</div>`;
    default: return '';
  }
}

/** A standalone, print-ready page. Every value is escaped; there is no script. */
function renderHtml(model, { revoked = false } = {}) {
  const f = model.footer || {};
  const banners = [
    revoked ? '<div class="banner">THIS DOCUMENT HAS BEEN REVOKED AND IS NOT VALID</div>' : '',
    f.official === false ? '<div class="banner note">STUDENT COPY - NOT AN OFFICIAL DOCUMENT</div>' : '',
  ].join('');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${esc(model.title)} ${esc(f.serial || '')}</title><style>${CSS}</style></head>
<body><div class="page">${banners}
<header><h1>${esc(model.university.name)}</h1>${model.university.address ? `<p>${esc(model.university.address)}</p>` : ''}</header>
<h2 class="doc">${esc(model.title)}</h2>
${model.blocks.map(renderBlock).join('\n')}
<footer>${f.serial ? `Serial no. ${esc(f.serial)} &nbsp;|&nbsp; Issued ${esc(f.issuedAt)} &nbsp;|&nbsp; Verification code ${esc(f.code)}<br>Verify this document at ${esc(f.verifyUrl)}<br>` : ''}Generated by ISDMS (TD-X Lab). This document is valid only with a matching serial number and verification code.</footer>
</div></body></html>`;
}

module.exports = { renderHtml };
